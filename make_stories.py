def story(rnd):
    hero = rnd.choice(HERO)
    s = [
        f"{SEASON[rnd.randrange(len(SEASON))]}, и {hero} жил {rnd.choice(PLACE)}.",
        f"У него была {rnd.choice(OWN)}, и больше он ничего не имел.",
        f"Однажды случилась беда: {rnd.choice(TROUBLE)}.",
        f"Люди сидели по домам и ждали, но никто не решался выйти.",
        f"Тогда {hero} собрался в дорогу и пошёл {rnd.choice(GO)}.",
        f"По пути он встретил {rnd.choice(MET)}.",
        f"Тот сказал ему: не спеши, {rnd.choice(ADVICE)}.",
        f"{rnd.choice(TEST)}.",
        f"К вечеру он нашёл {rnd.choice(FIND)}.",
        f"{rnd.choice(CLIMAX)}.",
        f"{rnd.choice(END)}.",
        f"{rnd.choice(MORAL)}.",
    ]
    if rnd.random() < 0.5:                       # немного разнообразия в длине
        s.pop(rnd.randrange(3, 8))
    return " ".join(s)


def main(n=140, path="stories.txt", seed=0):
    rnd = random.Random(seed)
    texts = [story(rnd) for _ in range(n)]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n\n".join(texts) + "\n")
    print(f"{n} рассказов, {sum(len(t.split()) for t in texts)} слов -> {path}")


if __name__ == "__main__":
    main()
